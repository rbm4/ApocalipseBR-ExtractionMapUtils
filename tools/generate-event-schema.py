"""Generate the Kahlua rules from the canonical JSON Schema; --check for CI."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "contracts/event-definition-v1.schema.json"
TARGET = ROOT / "ApocalipseBR-ExtractionMapUtils/common/media/lua/shared/ApocExtractionMapUtils_EventSchemaRules.lua"
EXAMPLE = ROOT / "contracts/examples/event-definition-v1.json"
FIXTURE = ROOT / "tests/fixtures/event-definition-v1.lua"


def lua(value, indent=0):
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (str, int, float)):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, list):
        return "{ " + ", ".join(lua(item, indent) for item in value) + " }"
    if isinstance(value, dict):
        pad = "    " * (indent + 1)
        return "{\n" + "\n".join(
            pad + "[" + json.dumps(key) + "] = " + lua(item, indent + 1) + ","
            for key, item in value.items()
        ) + "\n" + "    " * indent + "}"
    raise ValueError("Unsupported schema value")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = json.loads(SOURCE.read_text(encoding="utf-8"))
    # Patterns use a deliberately small ASCII subset with equivalent Lua syntax.
    # No executable source is accepted from event metadata.
    schema["$defs"]["id"]["pattern"] = "^[A-Za-z0-9_.%-]+$"
    result = "-- Generated by tools/generate-event-schema.py; edit contracts/event-definition-v1.schema.json.\nreturn " + lua(schema) + "\n"
    example = EXAMPLE.read_text(encoding="utf-8")
    json.loads(example)
    fixture = "-- Generated from contracts/examples/event-definition-v1.json.\nreturn [====[" + example + "]====]\n"
    for target, content in ((TARGET, result), (FIXTURE, fixture)):
        if args.check:
            if target.read_text(encoding="utf-8") != content:
                raise SystemExit("Generated event artifact is stale: " + target.name)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    if args.check:
        print("PASS: generated event rules and fixture match canonical JSON files")


if __name__ == "__main__":
    main()
